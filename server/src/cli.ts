import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createInterface } from 'node:readline/promises';
import { passwordSchema } from '@younes/contracts';
import { loadConfig, loadEnvFiles, REPO_ROOT, SERVER_ROOT } from './config.ts';
import { createDb } from './db/index.ts';
import { migrateDown, migrateToLatest, migrateToZero } from './db/migrate.ts';
import { diskStorage } from './lib/storage.ts';

/**
 * The server's command line (npm scripts in server/package.json):
 *   setup         write docker/.env and server/.env with fresh local secrets (fills only what's missing)
 *   migrate       apply every pending migration
 *   rollback      undo the latest migration
 *   seed [--demo] import the site's content; --demo adds the sample dashboard records (development)
 *   reset [--demo] development only: everything down, up again, seeded
 *   owner:create  create the studio owner (once - a second owner is refused)
 *   demo:add      add the sample dashboard records only (never the content import);
 *   demo:remove   remove them - on production both need --production (db/seed/demo.ts)
 */

/**
 * The seeds read the site's own source (src/data and the images it
 * imports), so they run from the source checkout (tsx), never from the
 * build: the built CLI (server/dist/cli.js) migrates and creates the owner.
 * The path is a variable so the bundler leaves it alone.
 */
async function fromSource<T>(where: string): Promise<T> {
  try {
    return await import(where);
  } catch (e) {
    if (import.meta.url.endsWith('.ts')) throw e;
    throw new Error('Seeding runs from the source checkout (npm run db:seed, npm run demo:add): it imports the site’s src/. The built CLI only migrates, rolls back and creates the owner.');
  }
}
const seeds = () => fromSource<typeof import('./db/seed/index.ts')>('./db/seed/index.ts');
const demo = () => fromSource<typeof import('./db/seed/demo.ts')>('./db/seed/demo.ts');

function printAdded(r: import('./db/seed/demo.ts').DemoAdded) {
  if (!r.added) return console.log('  Sample records are already there - nothing added. (demo:remove takes them out.)');
  console.log(`  + ${r.inquiries} sample inquiries, ${r.clients} sample clients, ${r.appointments} appointments, ${r.followUps} follow-ups${r.activity ? `, ${r.activity} history entries` : ''}`);
  for (const s of r.skipped) console.log(`  - skipped "${s.title}" (${s.startsAt}): a real appointment holds that time`);
}

const [command, ...args] = process.argv.slice(2);
const flag = (f: string) => args.includes(f);
const hex = (n: number) => randomBytes(n).toString('hex');

function readEnv(file: string): Map<string, string> {
  const m = new Map<string, string>();
  if (!existsSync(file)) return m;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const i = line.indexOf('=');
    if (i > 0 && !line.trimStart().startsWith('#')) m.set(line.slice(0, i).trim(), line.slice(i + 1).trim());
  }
  return m;
}

/** add the missing keys to an env file, keeping every existing line and value */
function fillEnv(file: string, header: string, wanted: [string, string][]) {
  const have = readEnv(file);
  const add = wanted.filter(([k]) => !have.has(k));
  if (!add.length) return 0;
  const prefix = existsSync(file) ? readFileSync(file, 'utf8').replace(/\s*$/, '\n') : `${header}\n`;
  writeFileSync(file, prefix + add.map(([k, v]) => `${k}=${v}`).join('\n') + '\n', { mode: 0o600 });
  return add.length;
}

async function setup() {
  const dockerEnv = path.join(REPO_ROOT, 'docker', '.env');
  const added = fillEnv(dockerEnv, '# Local Docker services - generated by `npm run setup`. Git-ignored. Never reuse in production.', [
    ['POSTGRES_PORT', '55432'],
    ['POSTGRES_SUPERUSER_PASSWORD', hex(24)],
    ['YOUNES_MIGRATOR_PASSWORD', hex(24)],
    ['YOUNES_APP_PASSWORD', hex(24)],
  ]);
  const d = readEnv(dockerEnv);
  const port = d.get('POSTGRES_PORT')!;
  const url = (role: string, pw: string, db: string) => `postgres://${role}:${pw}@127.0.0.1:${port}/${db}`;
  const app = d.get('YOUNES_APP_PASSWORD')!;
  const mig = d.get('YOUNES_MIGRATOR_PASSWORD')!;
  const serverEnv = path.join(SERVER_ROOT, '.env');
  const added2 = fillEnv(serverEnv, '# Local API settings - generated by `npm run setup`. Git-ignored. See server/README.md for every variable.', [
    ['NODE_ENV', 'development'],
    ['PORT', '3001'],
    ['DATABASE_URL', url('younes_app', app, 'younes_dev')],
    ['MIGRATION_DATABASE_URL', url('younes_migrator', mig, 'younes_dev')],
    ['TEST_DATABASE_URL', url('younes_app', app, 'younes_test')],
    ['TEST_MIGRATION_DATABASE_URL', url('younes_migrator', mig, 'younes_test')],
    ['PUBLIC_ORIGIN', 'http://localhost:5201'],
    ['TOTP_ENC_KEY', randomBytes(32).toString('base64')],
    ['OWNER_SETUP_TOKEN', hex(24)],
    ['SMTP_HOST', '127.0.0.1'],
    ['SMTP_PORT', '51025'],
    ['MAIL_FROM', 'Younes Tattoo <studio@localhost>'],
    ['AI_ENABLED', 'false'],
  ]);
  console.log(`docker/.env: ${added ? `${added} setting(s) added` : 'complete'}`);
  console.log(`server/.env: ${added2 ? `${added2} setting(s) added` : 'complete'}`);
  console.log('Next: npm run db:up, npm run db:migrate, npm run db:seed (and db:seed:demo for sample dashboard records).');
}

async function main() {
  if (command === 'setup') return setup();
  loadEnvFiles();
  const config = loadConfig();
  const storage = diskStorage(config.STORAGE_DIR);

  if (command === 'migrate' || command === 'rollback') {
    const db = createDb(config.MIGRATION_DATABASE_URL, { max: 1, applicationName: 'younes-migrate' });
    try {
      if (command === 'migrate') await migrateToLatest(db);
      else await migrateDown(db);
    } finally {
      await db.destroy();
    }
    return;
  }

  if (command === 'seed') {
    const db = createDb(config.DATABASE_URL, { max: 2, applicationName: 'younes-seed' });
    try {
      for (const l of await (await seeds()).seedContent(db, storage)) console.log(`  + ${l}`);
      if (flag('--demo')) {
        if (config.isProd) throw new Error('Refusing to add sample records to a production database. Use demo:add --production: it adds them without the content import.');
        printAdded(await (await demo()).addDemo(db, { activity: true }));
      }
      console.log('Seeded.');
    } finally {
      await db.destroy();
    }
    return;
  }

  if (command === 'reset') {
    const dbName = new URL(config.MIGRATION_DATABASE_URL).pathname.slice(1);
    if (config.NODE_ENV !== 'development' || !dbName.endsWith('_dev')) {
      throw new Error(`Refusing to reset "${dbName}": reset only runs with NODE_ENV=development on a *_dev database.`);
    }
    const mig = createDb(config.MIGRATION_DATABASE_URL, { max: 1, applicationName: 'younes-reset' });
    try {
      console.log(`Resetting ${dbName}…`);
      await migrateToZero(mig);
      await migrateToLatest(mig);
    } finally {
      await mig.destroy();
    }
    const db = createDb(config.DATABASE_URL, { max: 2 });
    try {
      for (const l of await (await seeds()).seedContent(db, storage)) console.log(`  + ${l}`);
      if (flag('--demo')) printAdded(await (await demo()).addDemo(db, { activity: true }));
    } finally {
      await db.destroy();
    }
    console.log('Reset complete. Stored files were kept; the owner account must be created again (npm run owner:create).');
    return;
  }

  if (command === 'demo:add' || command === 'demo:remove') {
    const d = await demo();
    // before anything touches the database
    d.assertDemoAllowed(config.isProd, args);
    const db = createDb(config.DATABASE_URL, { max: 2, applicationName: 'younes-demo' });
    try {
      if (command === 'demo:add') printAdded(await d.addDemo(db));
      else {
        const r = await d.removeDemo(db);
        console.log(`  - removed ${r.clients} sample clients, ${r.inquiries} inquiries, ${r.appointments} appointments, ${r.followUps} follow-ups (and ${r.notes} notes written on them)`);
        if (r.kept.length) {
          console.log(`  Kept ${r.kept.length} sample client(s) that real records now belong to - nothing of theirs was touched:`);
          for (const k of r.kept) console.log(`    ${k.name} (${k.id})`);
        }
      }
    } finally {
      await db.destroy();
    }
    return;
  }

  if (command === 'owner:create') {
    const { createOwner } = await import('./modules/auth/service.ts');
    const rl = createInterface({ input: process.stdin, output: process.stdout });
    const ask = async (q: string, env?: string) => process.env[env ?? ''] ?? (await rl.question(q)).trim();
    const name = await ask('Name: ', 'OWNER_NAME');
    const email = await ask('Email: ', 'OWNER_EMAIL');
    const password = await ask('Password (at least 12 characters - typed in the clear here; or set OWNER_PASSWORD): ', 'OWNER_PASSWORD');
    rl.close();
    const pw = passwordSchema.safeParse(password);
    if (!pw.success) throw new Error(pw.error.issues[0].message);
    const db = createDb(config.DATABASE_URL, { max: 1 });
    try {
      const user = await createOwner(db, { name, email, password });
      console.log(`Owner created: ${user.email}. Sign in at ${config.PUBLIC_ORIGIN}/studio - you'll set up two-factor on the first sign-in.`);
    } finally {
      await db.destroy();
    }
    return;
  }

  console.log('Commands: setup | migrate | rollback | seed [--demo] | reset [--demo] | owner:create | demo:add | demo:remove');
  process.exitCode = 1;
}

main().catch((e: unknown) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
